function renderSocialLink(item) {
  const path = BRAND_ICONS[item.platform];
  if (!path) return '';
  return joinLines([
    '          <li class="contact__social-item">',
    `            <a class="contact__social-link"${hrefAttr(item.href)} title="${escapeHtml(item.label)}">`,
    `              <svg viewBox="0 0 24 24" aria-hidden="true"><path d="${path}"></path></svg>`,
    '            </a>',
    '          </li>',
  ]);
}

// 表單（.contact__form）不吃 JSON 資料，維持手寫在兩段 BUILD 區塊中間；
// 品牌圖示列這次改排到表單下方置中，所以拆成獨立的 renderContactSocial()，
// 讓 index.html 可以用第二組 <!-- BUILD:contact-social:start/end --> 標記
// 插在表單之後，不用把整段表單也塞進 render 函式裡
function renderContactTop(data) {
  return joinLines([
    '        <div class="contact__prompt-bar">',
    '          <span class="contact__prompt-prefix">contact --intent</span>',
    `          <span class="contact__prompt-text">${escapeHtml(data.cta)}</span>`,
    '          <span class="contact__prompt-cursor" aria-hidden="true"></span>',
    '        </div>',
    `        <p class="contact__reply-note">${escapeHtml(data.replyNote)}</p>`,
    '        <p class="contact__text">',
    `          Email：<a class="contact__link" href="mailto:${escapeHtml(data.email)}">${escapeHtml(data.email)}</a>`,
    '        </p>',
  ]);
}

function renderContactSocial(data) {
  return joinLines([
    '        <ul class="contact__social-list">',
    data.socialLinks.map(renderSocialLink).join('\n'),
    '        </ul>',
  ]);
}

module.exports = { renderContactTop, renderContactSocial };
